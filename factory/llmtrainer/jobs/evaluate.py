"""``llmtrainer evaluate``: base vs specialist on the held-out (test-split-only) items, via the existing evalsuite.

Backends:
* ``stub``: deterministic toy subjects, offline. Plumbing only; the resulting EvaluationRun uses a stub evaluator and can
  never allow an improvement claim.
* ``hf``: real generation with transformers (+peft). Dry-run by default (prints the plan); ``execute=True`` loads local
  weights (never downloads unless ``allow_download``).
"""

